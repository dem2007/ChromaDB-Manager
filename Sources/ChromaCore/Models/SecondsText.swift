import Foundation

/// Время в секундах словами, когда округление даёт ноль (
/// правило 6: «Округление, дающее ноль, заменяется словами»).
///
/// «за 0.0 с» — число, которое молчит: оно не значит «мгновенно», оно значит
/// «здесь было измерение, и мы его потеряли». Правило было выписано в
/// дизайн-системе и жило одной частной функцией на экране «Замеры», а сводки
/// синхронизации и записи таблицы печатали сырой `%.1f` и показывали ноль на
/// каждой быстрой операции.
public enum SecondsText {

    /// Строка «<число> с» либо «меньше <шага> с», если число не дотягивает
    /// до первой значащей цифры.
    ///
    /// Ключи локализации — постоянные строки, а не собранные из кусков:
    /// переводчику достаётся целая фраза, а не «меньше» отдельно от числа.
    public static func line(_ seconds: Double, decimals: Int = 1) -> String {
        if decimals >= 2 {
            guard seconds >= 0.01 else { return String(localized: "меньше 0,01 с") }
            return String(format: String(localized: "%.2f с"), seconds)
        }
        guard seconds >= 0.1 else { return String(localized: "меньше 0,1 с") }
        return String(format: String(localized: "%.1f с"), seconds)
    }
}

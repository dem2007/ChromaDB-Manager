import Foundation

/// Сколько результатов приложение отдаёт за один поиск — **одно число на всё**
///.
///
/// Прежде их было три и они не совпадали: ползунок на экране поиска упирался
/// в 50, конвейер обрезал по 100, а ключу агента можно было выписать 500 —
/// и он молча получал сотню. Настройка обещала одно, приложение делало другое,
/// и понять, где именно оборвалось, было нельзя.
///
/// **Замер, из-за которого предел именно такой** (живая коллекция, 5765
/// чанков, запрос из шести слов):
///
/// | результатов | пул | векторный поиск | первые пять |
/// |---|---|---|---|
/// | 5 | 200 | 3 мс | — |
/// | 100 | 2000 | 153 мс | **те же** |
/// | 200 | 4000 | 310 мс | **те же** |
///
/// Первая пятёрка не меняется ни при каком пуле — то есть просьба о сотне
/// результатов не портит то, что настроено для пятёрки. Текстовая стадия
/// стоит около секунды **независимо** от пула: её цена в обходе коллекции
/// выражением, а не в числе возвращаемых кусков.
///
/// Поднять число выше можно — цена линейна и известна. Но менять его стоит
/// так же, как всё прочее здесь: замером, а не на глаз.
public enum RetrievalLimits {
    /// Потолок, общий для экрана поиска, конвейера и прав ключа агента.
    public static let maximumResults = 100
}

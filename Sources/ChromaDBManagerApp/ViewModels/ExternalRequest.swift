import Foundation

/// Просьба извне: из строки меню, из «Служб» Finder, из перетаскивания
/// или из интента Shortcuts.
///
/// Отдельным типом, а не набором флагов: главное окно разбирает такую
/// просьбу в одном месте, и добавление нового источника просьб не значит
/// переписывания окна.
enum ExternalRequest: Equatable {
    /// Показать коллекцию и подставить текст запроса.
    case search(collection: String?, text: String)
    /// Показать экран источников — после того, как папку перетащили на окно.
    case sources
    /// Спросить, что делать с файлами: добавить документами или
    /// зарегистрировать источником.
    case dropped(urls: [URL])
    /// Добавить текст в коллекцию: «Службы» и интент.
    case addText(String)
    /// Синхронизировать источник по идентификатору — интент Shortcuts.
    case syncSource(UUID)
}
